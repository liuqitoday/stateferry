export function currentLocale(): SupportedLocale {
  const value = typeof chrome !== 'undefined' && chrome.i18n?.getUILanguage
    ? chrome.i18n.getUILanguage()
    : typeof navigator !== 'undefined'
      ? navigator.language
      : undefined;
  return normalizeLocale(value);
}

export function getMessage(key: string, substitutions?: string | string[]): string {
  const locale = currentLocale();
  const chromeMessage = typeof chrome !== 'undefined' && chrome.i18n?.getMessage
    ? chrome.i18n.getMessage(key, substitutions)
    : '';
  const localizedFallback = fallback[locale][key];
  if (localizedFallback && locale !== 'en' && (!chromeMessage || chromeMessage === fallback.en[key])) return localizedFallback;
  if (chromeMessage) return chromeMessage;
  return localizedFallback ?? fallback.en[key] ?? key;
}
